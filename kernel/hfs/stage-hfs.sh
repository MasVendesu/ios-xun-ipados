#!/bin/bash
# Stage Apple's open source HFS as a built-in filesystem (bsd/xun_hfs) for the
# xun/SM6225 port. kernel/apply.sh runs this from the XNU source root before
# the patches are applied.
set -euo pipefail

[[ "${MACHINE:-}" == BCM2837 ]] || exit 0
[[ -f bsd/kern/bsd_init.c ]] || exit 1

# hfs-715.100.10 (2026-04-13) is the newest published HFS; the sources are
# taken at a fixed commit, never from a moving branch.
# The tag is fetched (a bare SHA is not a ref a shallow fetch can ask for) and the
# commit it must resolve to is checked below.
hfs_tag=hfs-715.100.10
hfs_sha=d1bac2f062e6e9c0dfcce302d9aacb10173d0eea
hfs_tmp=$(mktemp -d)
trap 'rm -rf "$hfs_tmp"' EXIT
git init -q "$hfs_tmp"
git -C "$hfs_tmp" fetch -q --depth 1 \
    https://github.com/apple-oss-distributions/hfs "refs/tags/$hfs_tag:refs/tags/$hfs_tag"
# the tag is annotated: peel it to the commit it points at
[[ "$(git -C "$hfs_tmp" rev-parse "refs/tags/$hfs_tag^{commit}")" == "$hfs_sha" ]] || {
    echo "hfs tag $hfs_tag does not point at $hfs_sha" >&2
    exit 1
}
git -C "$hfs_tmp" checkout -q "$hfs_sha"

python3 - "$hfs_tmp" <<'PY'
from pathlib import Path
import shutil
import sys

source = Path(sys.argv[1])
target = Path('bsd/xun_hfs')
if target.exists():
    raise SystemExit(f'refusing to overwrite existing HFS sources: {target}')
# Preserve upstream copyright/license headers; no downloaded sources in git.
for directory in ('core', 'hfs_encodings'):
    shutil.copytree(source / directory, target / directory)

# This kernel has no AppleKeyStore (content protection is not built, see
# xun_hfs_compat.h); its header is only needed for the key-wrapping API.
path = target / 'core' / 'hfs_iokit.h'
text = path.read_text()
include = '#include <AppleKeyStore/AppleKeyStoreFSServices.h>\n'
first = 'int hfs_unwrap_key('
end = '__END_DECLS'
if text.count(include) != 1 or text.count(first) != 1 or text.count(end) != 1:
    raise SystemExit(f'HFS source changed: {path}')
text = text.replace(include, '#if CONFIG_PROTECT\n' + include + '#endif\n')
i, j = text.index(first), text.index(end)
text = text[:i] + '#if CONFIG_PROTECT\n' + text[i:j].rstrip('\n') + '\n#endif\n\n' + text[j:]
path.write_text(text)
PY

# Kernel builds use -nostdinc; HFS's kext-config.h needs the SDK's target macros.
# On the CI runner that is macOS and xcrun knows the SDK; a plain Linux box can point
# TARGET_CONDITIONALS at a copy instead, otherwise the header below is generated.
hfs_tc=${TARGET_CONDITIONALS:-}
if [ -z "$hfs_tc" ] && command -v xcrun >/dev/null; then
    hfs_tc="$(xcrun --sdk macosx --show-sdk-path)/usr/include/TargetConditionals.h"
fi
if [ -n "$hfs_tc" ] && [ -f "$hfs_tc" ]; then
    cp "$hfs_tc" bsd/xun_hfs/
else
    cat > bsd/xun_hfs/TargetConditionals.h <<'EOF'
/* Generated by stage-hfs.sh: the iOS/OS X target macros HFS's kext-config.h
 * branches on. The kernel is built for iPhoneOS; OS X is only the fallback. */
#ifndef __TARGETCONDITIONALS__
#define __TARGETCONDITIONALS__
#define TARGET_OS_MAC 1
#define TARGET_OS_OSX 0
#define TARGET_OS_IPHONE 1
#define TARGET_OS_IOS 1
#define TARGET_OS_SIMULATOR 0
#define TARGET_OS_EMBEDDED 0
#endif
EOF
fi
echo "Staged hfs-715.100.10 ($hfs_sha)"
